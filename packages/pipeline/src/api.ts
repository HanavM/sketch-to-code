/**
 * Make this data real.
 *
 * Every prototype in the world renders from a literal at the top of the file:
 * `const users = [{…}, {…}]`, then `users.map(…)`. Turning that into an actual
 * endpoint is the least interesting work in software and it is the same work
 * every single time — define a route, move the records, fetch them, hold a
 * loading state, do not break the page while you do it. Four files' worth of
 * typing for a decision that was already made the moment someone said "these
 * should come from the server".
 *
 * So it happens by pointing at the list. The stamp on a rendered row names a
 * JSX node, the node sits inside a `.map()`, the map's callee is an identifier,
 * and babel can say — not guess — which declaration that identifier binds to.
 * From there the edit is mechanical, and everything that made it risky is
 * decidable up front.
 *
 * The literal STAYS in the component as a seed, which is the one decision here
 * worth defending. A promoted list that starts empty flashes blank on every
 * load, and — worse for this tool specifically — an edit that was supposed to
 * change nothing visible would change the first frame of the page, which is
 * exactly the signal the overlay uses to verify that an edit did no harm. With
 * the seed, first paint is byte-identical to what it was before, the diff reads
 * as "this data now also comes from a route", and a dead endpoint degrades to
 * the page the user already had instead of to a blank div.
 *
 * Two departures from the obvious shape, both forced by React rather than
 * chosen. The hook call cannot replace the module-level declaration where it
 * stands — `useApi()` at module scope runs outside a render and throws on
 * import, taking the whole page with it — so the renamed literal stays at
 * module scope and the hook call is inserted as the first statement of the
 * component that renders the list. And because the value now only exists
 * inside that component, any OTHER reader of the constant is a refusal: the
 * promotion would compile and then render stale data somewhere off-screen,
 * which is the failure mode this file exists to avoid.
 *
 * What it will not do, at all: no server is started, nothing is mounted, no
 * write path, no persistence. It writes a plain module a person can mount
 * later, and it points the component at the URL that module is meant to answer.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, relative, resolve } from 'node:path'
import { parse } from '@babel/parser'
import _traverse, { type Binding, type NodePath } from '@babel/traverse'
import type * as t from '@babel/types'
import { importAnchor } from './imports.js'

type TraverseFn = (ast: unknown, visitor: Record<string, unknown>) => void
const traverse = ((_traverse as unknown as { default?: unknown }).default ?? _traverse) as TraverseFn

export interface PromoteRequest {
  /** data-s2c stamp of an element inside the rendered list. */
  srcLoc: string
  /** Route name; defaults to the constant's own name, kebab-cased. */
  name?: string
}

export interface PromoteResult {
  ok: boolean
  /** e.g. '/api/users' */
  route?: string
  /** files written, project-relative */
  files?: string[]
  /** the component file that changed */
  from?: string
  /** how many records moved, for the receipt */
  count?: number
  change?: string
  error?: string
}

const STAMP = /^(.+):(\d+):(\d+)$/
const ROUTE_NAME = /^[a-z0-9]+(-[a-z0-9]+)*$/
const COMPONENT = /^[A-Z][\w$]*$/
/** Where the hook lives. One per project, shared by every promoted list. */
const HOOK_FILE = 'src/lib/useApi.ts'
const HOOK_NAME = 'useApi'
/**
 * Proof that a file on disk is one of ours.
 *
 * Only ever used to decide whether overwriting is allowed. Anything without it
 * is somebody's hand-written file, and this refuses rather than take it.
 */
const MARK = '@generated by sketch-to-code make-this-data-real'
/**
 * The phrase in a route file's header that records where its data came from.
 *
 * Read back on a re-promote: our own file for the same list can be rewritten,
 * our own file for a DIFFERENT list is two lists claiming one URL, and that is
 * a refusal rather than a race.
 */
const FROM = 'used to be a literal in'

const parseTs = (code: string): ReturnType<typeof parse> =>
  parse(code, { sourceType: 'module', plugins: ['jsx', 'typescript'] })

/** 'recentOrders' / 'RECENT_ORDERS' / 'Recent Orders' → 'recent-orders'. */
function kebab(raw: string): string {
  return raw
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .join('-')
    .toLowerCase()
}

/** 'recent-orders' → 'RecentOrders', for a type name. */
const pascal = (raw: string): string =>
  raw
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .map((w) => w[0]!.toUpperCase() + w.slice(1))
    .join('')

/** POSIX, extension-less, always relative — a specifier a bundler accepts. */
function specifierFor(fromDir: string, toAbs: string): string {
  const spec = relative(fromDir, toAbs).replace(/\\/g, '/').replace(/\.[jt]sx?$/, '')
  return spec.startsWith('.') ? spec : `./${spec}`
}

const indentAt = (code: string, index: number): string => {
  const lineStart = code.lastIndexOf('\n', index - 1) + 1
  return /^[ \t]*/.exec(code.slice(lineStart, index))![0]
}

const src = (code: string, n: t.Node): string =>
  n.start != null && n.end != null ? code.slice(n.start, n.end) : n.type

/** The enclosing function's name, when it has one worth quoting. */
function fnName(fn: NodePath): string | null {
  const n = fn.node
  if ((n.type === 'FunctionDeclaration' || n.type === 'FunctionExpression') && n.id) return n.id.name
  const parent = fn.parentPath
  if (parent?.isVariableDeclarator() && parent.node.id.type === 'Identifier') return parent.node.id.name
  return null
}

/**
 * What a node IS, in words, so a refusal can name what it actually found.
 *
 * Every branch here is a thing someone has really written inside a "data"
 * literal, and each one means something different about the fix: a call has to
 * be evaluated, a spread has to be flattened, an identifier has to be inlined.
 */
function describe(code: string, n: t.Node): string {
  switch (n.type) {
    case 'CallExpression':
    case 'NewExpression':
      return `a function call (\`${src(code, n)}\`)`
    case 'TemplateLiteral':
      return 'a template string'
    case 'TaggedTemplateExpression':
      return 'a tagged template'
    case 'SpreadElement':
      return `a spread (\`${src(code, n)}\`)`
    case 'Identifier':
      return `the identifier \`${n.name}\``
    case 'MemberExpression':
    case 'OptionalMemberExpression':
      return `a reference to \`${src(code, n)}\``
    case 'ArrowFunctionExpression':
    case 'FunctionExpression':
      return 'a function'
    case 'ObjectMethod':
      return 'a method'
    case 'ConditionalExpression':
      return 'a conditional'
    case 'BinaryExpression':
      return `an expression (\`${src(code, n)}\`)`
    case 'JSXElement':
    case 'JSXFragment':
      return 'JSX'
    default:
      return `\`${src(code, n)}\``
  }
}

/**
 * Is this literal something a route file could contain verbatim?
 *
 * The check is deep because the copy is verbatim. One identifier three levels
 * down — `{ icon: UserIcon }` — produces a route file that does not compile,
 * and the failure surfaces far from the gesture that caused it. Returns a
 * human sentence fragment naming the first offender and where it sits, or null
 * when the whole thing really is data.
 */
function dataFault(code: string, n: t.Node, where: string): string | null {
  switch (n.type) {
    case 'StringLiteral':
    case 'NumericLiteral':
    case 'BooleanLiteral':
    case 'NullLiteral':
      return null
    // `-1` and `+1` are two nodes but one number
    case 'UnaryExpression':
      return (n.operator === '-' || n.operator === '+') && n.argument.type === 'NumericLiteral'
        ? null
        : `${describe(code, n)} at ${where}`
    // A template with nothing interpolated is a string with different quotes
    case 'TemplateLiteral':
      return n.expressions.length === 0 ? null : `a template string at ${where}`
    case 'ArrayExpression': {
      for (let i = 0; i < n.elements.length; i++) {
        const el = n.elements[i]
        if (el == null) continue // a hole: `[, 1]` carries no value
        const fault = dataFault(code, el, `${where}[${String(i)}]`)
        if (fault) return fault
      }
      return null
    }
    case 'ObjectExpression': {
      for (const p of n.properties) {
        if (p.type !== 'ObjectProperty') return `${describe(code, p)} at ${where}`
        if (p.computed) return `a computed key at ${where}`
        const key =
          p.key.type === 'Identifier'
            ? p.key.name
            : p.key.type === 'StringLiteral'
              ? p.key.value
              : p.key.type === 'NumericLiteral'
                ? String(p.key.value)
                : null
        if (key == null) return `a key that is ${describe(code, p.key)} at ${where}`
        const fault = dataFault(code, p.value, `${where}.${key}`)
        if (fault) return fault
      }
      return null
    }
    default:
      return `${describe(code, n)} at ${where}`
  }
}

/** The `X` in `X.map(…)`, when the list is rendered from a plain name. */
interface ListSource {
  call: NodePath<t.CallExpression>
  callee: t.MemberExpression
  object: NodePath<t.Identifier>
}

/**
 * The nearest `.map()` the pointed-at element is rendered by.
 *
 * Nearest, and then judged — never "keep climbing until something fits". An
 * element inside `{r.tags.map(…)}` is a tag, and promoting the outer `rows`
 * because `r.tags` did not qualify would move data the user was not pointing
 * at and report success about it.
 */
function enclosingMap(el: NodePath): NodePath<t.CallExpression> | null {
  for (let at: NodePath | null = el; at; at = at.parentPath) {
    const parent: NodePath | null = at.parentPath
    if (!parent?.isCallExpression()) continue
    // in the ARGUMENTS, not in the receiver: `f(row).map(…)` has the element in
    // its callee, and that call renders nothing of ours
    if (!(parent.node.arguments as t.Node[]).includes(at.node)) continue
    const callee = parent.node.callee
    if (
      (callee.type === 'MemberExpression' || callee.type === 'OptionalMemberExpression') &&
      !callee.computed &&
      callee.property.type === 'Identifier' &&
      callee.property.name === 'map'
    ) {
      return parent
    }
  }
  return null
}

/**
 * The component the hook call has to go into.
 *
 * `getFunctionParent()` from inside a list returns the map callback, so
 * callbacks are stepped over: a function that is itself an argument to a call
 * is not where React runs hooks.
 */
function componentOwner(from: NodePath): NodePath<t.Function> | null {
  let fn = from.getFunctionParent()
  while (fn) {
    const p: NodePath | null = fn.parentPath
    if (p?.isCallExpression() && (p.node.arguments as t.Node[]).includes(fn.node)) {
      fn = p.getFunctionParent()
      continue
    }
    return fn
  }
  return null
}

/** `const [x, setX] = useState(…)` — including `React.useState`. */
function isUseState(init: t.Node | null | undefined): boolean {
  if (init?.type !== 'CallExpression') return false
  const c = init.callee
  if (c.type === 'Identifier') return c.name === 'useState'
  return c.type === 'MemberExpression' && !c.computed && c.property.type === 'Identifier' && c.property.name === 'useState'
}

/** `useApi('/api/users', users_SEED)` — the shape this file itself writes. */
function useApiRoute(init: t.Node | null | undefined): string | null {
  if (init?.type !== 'CallExpression') return null
  if (init.callee.type !== 'Identifier' || init.callee.name !== HOOK_NAME) return null
  const first = init.arguments[0]
  return first?.type === 'StringLiteral' ? first.value : ''
}

/**
 * Why a parameter cannot be promoted — and each kind of parameter has its own
 * fix, which is the only reason to tell them apart.
 */
function paramRefusal(code: string, name: string, binding: Binding, rel: string): string {
  const fn = binding.path.parentPath
  const call = fn?.parentPath
  if (fn && call?.isCallExpression() && (call.node.arguments as t.Node[]).includes(fn.node)) {
    const callee = call.node.callee
    const listed = callee.type === 'MemberExpression' ? `{${src(code, callee)}(…)}` : 'the list around it'
    return (
      `\`${name}\` is the parameter of the enclosing ${listed}, so it is one row of a bigger list, not a list of its own. ` +
      `Point at a row of that outer list instead.`
    )
  }
  if (fn?.isFunction()) {
    const owner = fnName(fn)
    const index = (fn.node.params as t.Node[]).indexOf(binding.path.node)
    if (owner && COMPONENT.test(owner) && index === 0) {
      return (
        `\`${name}\` is a prop of ${owner}, so the data is passed in from somewhere else and there is nothing in ${rel} to move. ` +
        `Promote it where the array is actually written — the file that renders <${owner} ${name}={…} />.`
      )
    }
    if (owner) {
      return (
        `\`${name}\` is a parameter of ${owner}(), so its value arrives from each caller rather than being written down. ` +
        `Promote a \`const ${name} = […]\` declared at the top of ${rel} instead.`
      )
    }
  }
  return (
    `\`${name}\` is a function parameter, so its value comes from the caller rather than from this file. ` +
    `Promote a \`const ${name} = […]\` declared at the top of ${rel} instead.`
  )
}

/** Does this file already export something called `useApi`? */
function exportsUseApi(code: string): boolean {
  let found = false
  let ast
  try {
    ast = parseTs(code)
  } catch {
    return false
  }
  for (const stmt of ast.program.body) {
    if (stmt.type !== 'ExportNamedDeclaration') continue
    const d = stmt.declaration
    if (d?.type === 'FunctionDeclaration' && d.id?.name === HOOK_NAME) found = true
    if (d?.type === 'VariableDeclaration') {
      for (const decl of d.declarations) {
        if (decl.id.type === 'Identifier' && decl.id.name === HOOK_NAME) found = true
      }
    }
    for (const s of stmt.specifiers) {
      if (s.type === 'ExportSpecifier') {
        const as = s.exported.type === 'Identifier' ? s.exported.name : s.exported.value
        if (as === HOOK_NAME) found = true
      }
    }
  }
  return found
}

/**
 * The hook, written once per project.
 *
 * Kept as source text rather than generated, because there is nothing about it
 * to vary: the whole contract is "seed now, server later, seed again if the
 * server is not there".
 */
const HOOK_SOURCE = `/**
 * One URL, one seed, no dependencies.
 *
 * Everything promoted out of a literal comes through here, and the seed is the
 * point of it. The component already had its data written down, so first paint
 * can be exactly what it was before the endpoint existed — no empty flash, and
 * no visual change to explain for an edit that was meant to change nothing you
 * can see.
 *
 * Failure keeps the seed instead of throwing: a prototype whose API server is
 * not running should still render the page it rendered yesterday. It says so on
 * the console once, because silence is how a dead endpoint survives all the way
 * to production.
 *
 * ${MARK}
 */
import { useEffect, useState } from 'react'

export function ${HOOK_NAME}<T>(url: string, seed: T): T {
  const [data, setData] = useState<T>(seed)

  useEffect(() => {
    // the component can unmount mid-flight, and setting state after that is a
    // warning in the console for no benefit
    let live = true
    void (async () => {
      try {
        const res = await fetch(url)
        if (!res.ok) throw new Error(\`\${String(res.status)} \${res.statusText}\`)
        const next = (await res.json()) as T
        if (live) setData(next)
      } catch (err) {
        console.warn(\`${HOOK_NAME}: \${url} did not answer, keeping the seed —\`, err)
      }
    })()
    return () => {
      live = false
    }
    // url only: the seed is where this starts, not an input to the request, and
    // a fresh literal every render would re-fetch forever
  }, [url])

  return data
}
`

/** What the literal holds, counted: records for a list, fields for an object. */
const heldNoun = (kind: 'list' | 'object', count: number): string =>
  `${kind === 'list' ? 'record' : 'field'}${count === 1 ? '' : 's'}`

/**
 * The route file.
 *
 * A plain module with no framework imports, because the framework is not
 * decided yet — this runs on a prototype, and the whole promise is that the
 * file can be mounted later by whatever the prototype becomes. So it exports
 * the records and a `GET` that returns them, which Express, a Next route
 * handler, a test, or a script can each use without rewriting anything. The
 * type is read off the data with `typeof`, so it cannot drift from it, and no
 * shape is invented for records nobody has typed yet.
 */
function routeSource(
  route: string,
  name: string,
  literal: string,
  fromRel: string,
  count: number,
  kind: 'list' | 'object',
): string {
  const base = pascal(kebab(name))
  const typeName = base + 'Data' === name ? `${base}Payload` : `${base}Data`
  const assertion = kind === 'list' ? 'expect(GET())' : 'expect(Object.keys(GET()))'
  const held = heldNoun(kind, count)
  return (
    `/**\n` +
    ` * ${route} — the ${kind} that ${FROM} ${fromRel}.\n` +
    ` *\n` +
    ` * Deliberately a plain module: no framework imports, nothing to install, and\n` +
    ` * nothing running yet. It exports the data and a GET that returns it, which is\n` +
    ` * the smallest thing each of these can mount as-is:\n` +
    ` *\n` +
    ` *   express   app.get('${route}', (_req, res) => { res.json(GET()) })\n` +
    ` *   next      export function GET() { return Response.json(${name}) }\n` +
    ` *   test      ${assertion}.toHaveLength(${String(count)})\n` +
    ` *\n` +
    ` * ${fromRel} still holds these ${String(count)} ${held} as its seed, so the page\n` +
    ` * renders identically before the first response and if there is never one.\n` +
    ` *\n` +
    ` * ${MARK}\n` +
    ` */\n` +
    `export const ${name} = ${literal}\n` +
    `\n` +
    `/** What ${route} answers with, read off the data so it cannot drift from it. */\n` +
    `export type ${typeName} = typeof ${name}\n` +
    `\n` +
    `export function GET(): ${typeName} {\n` +
    `  return ${name}\n` +
    `}\n`
  )
}

export function promoteToApi(root: string, req: PromoteRequest): PromoteResult {
  const m = STAMP.exec(req.srcLoc ?? '')
  if (!m) return { ok: false, error: `bad source location "${String(req.srcLoc)}"` }
  const rel = m[1]!
  const line = Number(m[2])
  const col = Number(m[3])

  const abs = resolve(root, rel)
  if (!abs.startsWith(resolve(root))) return { ok: false, error: 'that source location escapes the app root' }

  let code: string
  try {
    code = readFileSync(abs, 'utf8')
  } catch {
    return { ok: false, error: `cannot read ${rel}` }
  }
  let ast
  try {
    ast = parseTs(code)
  } catch {
    return { ok: false, error: `cannot parse ${rel} — fix what is broken there and try again` }
  }

  // ── the element, and the list that renders it ──
  let open: NodePath<t.JSXOpeningElement> | undefined
  traverse(ast, {
    JSXOpeningElement(path: NodePath<t.JSXOpeningElement>) {
      const loc = path.node.loc
      if (loc && loc.start.line === line && loc.start.column + 1 === col) open = path
    },
  })
  if (!open) return { ok: false, error: `no element at ${req.srcLoc} (stale stamp?)` }

  const call = enclosingMap(open)
  if (!call) {
    return {
      ok: false,
      error:
        `that element is not rendered by a list, so there are no records to move. ` +
        `Point at one of the rows a {…map(…)} repeats.`,
    }
  }
  const callee = call.node.callee
  if (callee.type !== 'MemberExpression' && callee.type !== 'OptionalMemberExpression') {
    return { ok: false, error: 'that list is not a `.map()` over anything nameable — point at a row of a {items.map(…)}' }
  }
  const objNode = callee.object
  if (objNode.type !== 'Identifier') {
    const shown = src(code, objNode)
    return {
      ok: false,
      error:
        `that list renders from \`${shown}.map(…)\`, and \`${shown}\` is not a constant of its own — ` +
        `an endpoint needs one named list. Pull it out as \`const … = ${shown}\` at the top of ${rel}, ` +
        `render from that, and point at a row again.`,
    }
  }
  const calleePath = call.get('callee') as NodePath<t.MemberExpression>
  const objPath = calleePath.get('object') as NodePath<t.Identifier>
  const name = objNode.name

  // ── which declaration is that, really? ──
  const binding = objPath.scope.getBinding(name)
  if (!binding) {
    return {
      ok: false,
      error:
        `\`${name}\` is not declared anywhere in ${rel} — it resolves to a global, so there is no literal to move. ` +
        `Declare the list as a \`const\` at the top of ${rel} and point at a row again.`,
    }
  }
  const declarator = binding.path.isVariableDeclarator() ? binding.path : null
  const init = declarator?.node.init ?? null

  // Already ours: check before anything else, because a promoted list's
  // identifier now binds to a const INSIDE the component, which every test
  // below would report as some other, more confusing problem.
  const already = useApiRoute(init)
  if (already != null) {
    return {
      ok: false,
      error:
        `\`${name}\` already comes from an endpoint: ${rel} calls ${HOOK_NAME}(${already ? `'${already}'` : '…'}, …). ` +
        `Edit server/api/${already ? kebab(already.replace(/^\/api\//, '')) : kebab(name)}.ts to change the data.`,
    }
  }

  if (binding.kind === 'module') {
    const decl = binding.path.parentPath
    const from = decl?.isImportDeclaration() ? decl.node.source.value : 'another module'
    return {
      ok: false,
      error:
        `\`${name}\` is imported from '${from}', so the literal is not in ${rel} and this cannot move it from here. ` +
        `Move the array into ${rel} and promote it, or write the route by hand from '${from}'.`,
    }
  }
  if (binding.kind === 'param') {
    return { ok: false, error: paramRefusal(code, name, binding, rel) }
  }
  if (isUseState(init)) {
    return {
      ok: false,
      error:
        `\`${name}\` is React state (useState), so something already replaces it while the page runs and a fetch would ` +
        `fight that. Promote the module-level \`const\` you seed the state with, or fetch into this state yourself.`,
    }
  }
  if (!declarator || binding.kind !== 'const') {
    const what =
      binding.kind === 'let' || binding.kind === 'var'
        ? `declared with \`${binding.kind}\`, so something reassigns it`
        : `not a \`const\` — it is ${binding.kind === 'hoisted' ? 'a function or class declaration' : `bound as ${binding.kind}`}`
    return {
      ok: false,
      error:
        `\`${name}\` is ${what}. A promoted list is read-only data; declare it as \`const ${name} = […]\` at the top of ${rel} ` +
        `and promote that.`,
    }
  }
  if (declarator.node.id.type !== 'Identifier') {
    return {
      ok: false,
      error:
        `\`${name}\` is destructured out of ${init ? describe(code, init) : 'something else'}, so there is no literal of its own to move. ` +
        `Give the list its own \`const ${name} = […]\` at the top of ${rel} and promote that.`,
    }
  }
  if (binding.scope.block.type !== 'Program') {
    const owner = binding.scope.path.isFunction() ? fnName(binding.scope.path) : null
    return {
      ok: false,
      error:
        `\`${name}\` is declared inside ${owner ? `${owner}()` : 'a function'}, not at the top level of ${rel}. ` +
        `Move it above the component, to module scope, and promote it there.`,
    }
  }
  const declPath = declarator.parentPath
  if (!declPath.isVariableDeclaration()) {
    return { ok: false, error: `cannot find the declaration of \`${name}\` in ${rel}` }
  }
  if (declPath.node.declarations.length > 1) {
    const others = declPath.node.declarations
      .filter((d) => d !== declarator.node)
      .map((d) => (d.id.type === 'Identifier' ? `\`${d.id.name}\`` : 'another name'))
    return {
      ok: false,
      error:
        `\`${name}\` shares one \`const\` statement with ${others.join(', ')}, and only part of it can move. ` +
        `Give \`${name}\` its own \`const\` line and promote it again.`,
    }
  }
  if (declPath.parentPath?.isExportNamedDeclaration()) {
    return {
      ok: false,
      error:
        `\`${name}\` is exported from ${rel}, so other files import the literal directly. A fetched value only exists ` +
        `inside the component that fetches it, so the export would go stale. Remove the \`export\` (or have those files ` +
        `read the route instead) and promote it again.`,
    }
  }

  // ── is the initialiser actually data? ──
  if (!init) {
    return { ok: false, error: `\`${name}\` is declared without a value, so there is nothing to serve` }
  }
  if (init.type !== 'ArrayExpression' && init.type !== 'ObjectExpression') {
    return {
      ok: false,
      error:
        `\`${name}\` is ${describe(code, init)}, not data written out — an endpoint can only serve records that are ` +
        `already literal. Replace it with the array it produces, then promote that.`,
    }
  }
  const fault = dataFault(code, init, name)
  if (fault) {
    return {
      ok: false,
      error:
        `\`${name}\` is not plain data: it contains ${fault}. The route file gets the literal verbatim, and that would ` +
        `not resolve there. Replace it with the value it stands for, then promote again.`,
    }
  }
  if (init.start == null || init.end == null) {
    return { ok: false, error: `the literal has no source positions — reload the page and try again` }
  }
  const literal = code.slice(init.start, init.end)
  const kind = init.type === 'ArrayExpression' ? 'list' : 'object'
  const count = init.type === 'ArrayExpression' ? init.elements.length : init.properties.length

  // ── who else reads it? ──
  const owner = componentOwner(call)
  if (!owner) {
    return {
      ok: false,
      error:
        `that list is not rendered inside a function, so there is no component to fetch from. ` +
        `Render it from a component and promote it again.`,
    }
  }
  const ownerName = fnName(owner)
  if (!ownerName || !COMPONENT.test(ownerName)) {
    return {
      ok: false,
      error:
        `the list is rendered by ${ownerName ? `${ownerName}()` : 'an anonymous function'}, which is not a React component, ` +
        `so a hook cannot run there. Move the list into the component that renders it and promote it again.`,
    }
  }
  const body = owner.node.body
  if (body.type !== 'BlockStatement' || body.start == null) {
    return {
      ok: false,
      error:
        `${ownerName} returns its JSX directly, so there is no room in it for the fetch. Give it a block body ` +
        `(\`${ownerName} = () => { return … }\`) and promote it again.`,
    }
  }
  const strayed = binding.referencePaths.filter((r) => r !== objPath && !r.findParent((p) => p === owner))
  if (strayed.length) {
    const at = strayed[0]!
    const elsewhere = componentOwner(at)
    const where = elsewhere ? (fnName(elsewhere) ?? 'another function') : 'module scope'
    const atLine = at.node.loc?.start.line
    return {
      ok: false,
      error:
        `\`${name}\` is also read in ${where}${atLine ? ` (line ${String(atLine)})` : ''}, and a fetched list only exists ` +
        `inside ${ownerName}. Promote a list that just one component reads, or lift the shared use into a prop first.`,
    }
  }

  // ── names ──
  const routeName = kebab(req.name ?? name)
  if (!ROUTE_NAME.test(routeName)) {
    return {
      ok: false,
      error:
        `"${String(req.name ?? name)}" does not make a usable route name — use lowercase letters, digits and dashes, ` +
        `like 'recent-orders'.`,
    }
  }
  const route = `/api/${routeName}`
  const routeRel = `server/api/${routeName}.ts`
  const routeAbs = join(root, routeRel)
  if (existsSync(routeAbs)) {
    let existing = ''
    try {
      existing = readFileSync(routeAbs, 'utf8')
    } catch {
      existing = ''
    }
    // Our own file for THIS list is fair game to rewrite — re-promoting after
    // someone undid the component edit is the same intent as the first time.
    // Anything else is somebody's work, and taking it silently is unforgivable.
    if (!existing.includes(MARK)) {
      return {
        ok: false,
        error:
          `${routeRel} already exists and was not written by this tool, so promoting \`${name}\` would overwrite it. ` +
          `Pass a different name for the route, or delete that file if it is stale.`,
      }
    }
    if (!existing.includes(`${FROM} ${rel}.`)) {
      const other = new RegExp(`${FROM} (\\S+?)\\.\\n`).exec(existing)?.[1]
      return {
        ok: false,
        error:
          `${route} is already served from ${routeRel}, promoted out of ${other ?? 'another file'} — two lists cannot ` +
          `share one route. Pass a different name for this one.`,
      }
    }
  }

  const seedName = `${name}_SEED`
  if (binding.scope.hasBinding(seedName) || owner.scope.hasBinding(seedName)) {
    return {
      ok: false,
      error:
        `${rel} already declares \`${seedName}\`, which is the name the literal needs. Rename it and promote again.`,
    }
  }

  // Reusing an existing `useApi` import is what makes a second list in the same
  // file work; a second import line would be a duplicate declaration.
  const hookAbs = join(root, HOOK_FILE)
  let hookImported = false
  let hookClash = false
  for (const stmt of ast.program.body) {
    if (stmt.type !== 'ImportDeclaration') continue
    const specAbs = resolve(dirname(abs), stmt.source.value)
    const sameModule =
      ['', '.ts', '.tsx', '.js', '.jsx'].some((e) => specAbs + e === hookAbs) ||
      // an aliased path ('@/lib/useApi') resolves to nothing from here, but it
      // is plainly the same module, and refusing it would be a lie
      /(^|\/)lib\/useApi(\.[jt]sx?)?$/.test(stmt.source.value)
    for (const s of stmt.specifiers) {
      if (s.local.name !== HOOK_NAME) continue
      if (sameModule && s.type === 'ImportSpecifier') hookImported = true
      else hookClash = true
    }
  }
  if (!hookImported && (hookClash || owner.scope.hasBinding(HOOK_NAME))) {
    return {
      ok: false,
      error:
        `${rel} already has its own \`${HOOK_NAME}\`, which is not the hook this writes. Rename it and promote again.`,
    }
  }

  // ── the hook file: write it once, never over someone else's ──
  let hookSource: string | null = null
  if (existsSync(hookAbs)) {
    let existing = ''
    try {
      existing = readFileSync(hookAbs, 'utf8')
    } catch {
      return { ok: false, error: `cannot read ${HOOK_FILE}` }
    }
    // A project that already has this hook keeps it: theirs may do retries,
    // auth, a base URL. Only the shape matters, and the import has to resolve.
    if (!exportsUseApi(existing)) {
      return {
        ok: false,
        error:
          `${HOOK_FILE} already exists but does not export \`${HOOK_NAME}\`, so the import would not resolve. ` +
          `Rename that file, or add a \`${HOOK_NAME}(url, seed)\` export to it, and promote again.`,
      }
    }
  } else {
    hookSource = HOOK_SOURCE
  }

  // ── build the three edits, then check everything parses before writing ──
  const idNode = declarator.node.id
  if (idNode.start == null || idNode.end == null) {
    return { ok: false, error: `the declaration of \`${name}\` has no source positions — reload and try again` }
  }
  const firstStmt = body.body[0]
  const bodyIndent = firstStmt?.start != null ? indentAt(code, firstStmt.start) : `${indentAt(code, owner.node.start ?? 0)}  `
  const hookCall = `const ${name} = ${HOOK_NAME}('${route}', ${seedName})`
  const importLine = hookImported ? '' : `import { ${HOOK_NAME} } from '${specifierFor(dirname(abs), hookAbs)}'\n`

  const edits: { start: number; end: number; text: string }[] = [
    { start: idNode.start, end: idNode.end, text: seedName },
    { start: body.start + 1, end: body.start + 1, text: `\n${bodyIndent}${hookCall}` },
  ]
  if (importLine) {
    // the anchor comes from the AST, not from a `^import` match — imports.ts
    // explains the bug that taught every engine here to ask babel
    const at = importAnchor(ast, code)
    // anchor 0 means the file had no imports at all, so the new line would
    // otherwise weld itself onto whatever the file actually opens with
    edits.push({ start: at, end: at, text: at === 0 ? `${importLine}\n` : importLine })
  }
  // later offsets first, so each earlier edit's positions are still the ones
  // babel reported
  edits.sort((a, b) => b.start - a.start)
  let next = code
  for (const e of edits) next = next.slice(0, e.start) + e.text + next.slice(e.end)

  const routeText = routeSource(route, name, literal, rel, count, kind)
  const outputs: [string, string][] = [
    [rel, next],
    [routeRel, routeText],
  ]
  if (hookSource) outputs.push([HOOK_FILE, hookSource])
  // nothing is written until every file that would be written parses
  for (const [what, text] of outputs) {
    try {
      parseTs(text)
    } catch (err) {
      return { ok: false, error: `promoting \`${name}\` would leave ${what} unparseable (${String(err)})` }
    }
  }

  mkdirSync(dirname(routeAbs), { recursive: true })
  writeFileSync(routeAbs, routeText)
  if (hookSource) {
    mkdirSync(dirname(hookAbs), { recursive: true })
    writeFileSync(hookAbs, hookSource)
  }
  writeFileSync(abs, next)

  return {
    ok: true,
    route,
    files: hookSource ? [routeRel, HOOK_FILE] : [routeRel],
    from: rel,
    count,
    change:
      `${String(count)} ${heldNoun(kind, count)} moved to ${routeRel} · ` +
      `${ownerName} now reads ${route}, seeded from \`${seedName}\` so first paint is unchanged`,
  }
}

/**
 * Draw a link: an arrow from a button to a box with a screen's name in it.
 *
 * The first thing a person builds past one page is a second page, and the
 * drawing-first way to say "this goes there" is an arrow — no words beyond the
 * screen's own name. Everything after recognising that gesture is mechanical
 * and the same every time: a file for the new screen, a way for the page to
 * show it, and the button pointed at it. So, like `save` and `serve`, it is an
 * engine and not a prompt: the model's job is to say which button and what the
 * screen is called, and this file writes the rest identically every time.
 *
 * The decisions, and why (docs/navigation.md has the long form):
 *
 * Hash routes (`#/pricing`), not history routes. A history route needs every
 * host the app is ever put on to answer `/pricing` with index.html; a hash
 * route needs nothing from anyone, which is the right default for someone who
 * does not know what a server fallback is. Browser back works for free (it is
 * a `hashchange`), and the `#/` prefix keeps it clear of in-page anchors like
 * `#features`, which still scroll as before.
 *
 * No router dependency. Thirty lines in `src/lib/screens.tsx` cover show /
 * open / back, and adding `react-router-dom` to someone's package.json is an
 * install step that can fail, behind a gesture that should be instant.
 *
 * An app that already has a router never gets these hash screens: its routes
 * are the truth about its screens, and a second, parallel system next to them
 * is two answers to "what's on this URL". react-router apps get a page in
 * their own route table instead (navigate-router.ts, s2c-041); other routers
 * (TanStack, wouter, reach) are refused by name.
 *
 * The page is switched where the app is mounted, not inside App. `main.tsx`'s
 * `<App />` becomes `<Screens home={<App />} screens={screens} />`: App's code
 * is not touched, so nothing the user built can break, and the home screen is
 * exactly the page they were drawing on.
 *
 * Undo needs nothing here: every file this writes or edits is in the working
 * tree, and the run's capture/revert puts all of them back in one step,
 * created files included.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, relative, resolve } from 'node:path'
import { parse } from '@babel/parser'
import _traverse, { type NodePath } from '@babel/traverse'
import type * as t from '@babel/types'
import { importAnchor } from './imports.js'
import { linkToRouterScreen } from './navigate-router.js'

type TraverseFn = (ast: unknown, visitor: Record<string, unknown>) => void
const traverse = ((_traverse as unknown as { default?: unknown }).default ?? _traverse) as TraverseFn

export interface NavigateRequest {
  /** data-s2c stamp of the button or link the arrow starts at. */
  srcLoc: string
  /** The screen's name as written in the box the arrow points at: "Pricing", "Sign up". */
  screen: string
}

export interface NavigateResult {
  ok: boolean
  /** The hash route, e.g. '#/pricing'. */
  route?: string
  /** The screen's file, repo-relative — absent when it already existed. */
  screenFile?: string
  /** Every file created or edited, repo-relative. */
  files?: string[]
  /** True when the screen was already there and only the link was added. */
  reused?: boolean
  /** The screen's file, repo-relative, new or already there (s2c-040 builds into it). */
  screenAt?: string
  /** The screen's name as its heading shows it. */
  title?: string
  change?: string
  error?: string
}

const STAMP = /^(.+):(\d+):(\d+)$/
const LIB_FILE = 'src/lib/screens.tsx'
const REGISTRY_FILE = 'src/screens/index.ts'
const MARK = '@generated by sketch-to-code draw-a-link'
/** Packages that mean "this app already decides what is on each URL". */
const ROUTERS = ['react-router-dom', 'react-router', '@tanstack/react-router', 'wouter', '@reach/router']
const MAIN_CANDIDATES = ['src/main.tsx', 'src/main.jsx', 'src/index.tsx', 'src/index.jsx', 'src/main.ts', 'src/main.js']

const parseTs = (code: string): ReturnType<typeof parse> =>
  parse(code, { sourceType: 'module', plugins: ['jsx', 'typescript'] })

/** 'Sign up!' → 'sign-up'. */
export function screenSlug(raw: string): string {
  return raw
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .join('-')
    .toLowerCase()
}

/** 'sign-up' → 'SignUp'; a name starting with a digit gets a prefix so it is a valid identifier. */
function pascal(slug: string): string {
  const p = slug.split('-').filter(Boolean).map((w) => w[0]!.toUpperCase() + w.slice(1)).join('')
  return /^[0-9]/.test(p) ? `Screen${p}` : p
}

/** 'sign-up' → 'Sign up', for the screen's heading when the user wrote it in lower case. */
export function screenTitle(raw: string): string {
  const words = raw.trim().replace(/\s+/g, ' ')
  return words[0]!.toUpperCase() + words.slice(1)
}

function specifierFor(fromDir: string, toAbs: string): string {
  const spec = relative(fromDir, toAbs).replace(/\\/g, '/').replace(/\.[jt]sx?$/, '').replace(/\/index$/, '')
  return spec.startsWith('.') ? spec : `./${spec}`
}

function readJson(path: string): Record<string, unknown> | null {
  try {
    return JSON.parse(readFileSync(path, 'utf8')) as Record<string, unknown>
  } catch {
    return null
  }
}

/** The router this app already has, if any. */
export function existingRouter(root: string): string | null {
  const pkg = readJson(join(root, 'package.json'))
  if (!pkg) return null
  const deps = { ...(pkg.dependencies as object | undefined), ...(pkg.devDependencies as object | undefined) }
  return ROUTERS.find((r) => r in deps) ?? null
}

function usesTailwind(root: string): boolean {
  const pkg = readJson(join(root, 'package.json'))
  if (!pkg) return false
  const deps = { ...(pkg.dependencies as object | undefined), ...(pkg.devDependencies as object | undefined) }
  return 'tailwindcss' in deps
}

const attrNamed = (open: t.JSXOpeningElement, name: string): t.JSXAttribute | null => {
  for (const a of open.attributes) {
    if (a.type === 'JSXAttribute' && a.name.type === 'JSXIdentifier' && a.name.name === name) return a
  }
  return null
}

const hostTag = (open: t.JSXOpeningElement): string | null =>
  open.name.type === 'JSXIdentifier' && /^[a-z]/.test(open.name.name) ? open.name.name : null

// ───────────────────────── generated files ─────────────────────────

const LIB_SOURCE = `// ${MARK}
// Screens for this app, switched by the part of the address after "#/".
// Kept dependency-free on purpose: no router to install, and browser back works.
import { useEffect, useState, type ComponentType, type ReactNode } from 'react'

const current = (): string | null => {
  const m = /^#\\/([a-z0-9-]+)/.exec(window.location.hash)
  return m ? m[1]! : null
}

/** How many screens were opened from inside the app, so back never leaves it. */
let opened = 0

/** Show a screen by name: openScreen('pricing') shows #/pricing. */
export function openScreen(name: string): void {
  opened += 1
  window.location.hash = \`#/\${name}\`
  window.scrollTo(0, 0)
}

/** Go back to where the user came from — the home page if they arrived here directly. */
export function goBack(): void {
  if (opened > 0) {
    opened -= 1
    window.history.back()
  } else {
    window.location.hash = ''
  }
}

/** Renders the screen the address names, or the home page. */
export function Screens({ home, screens }: { home: ReactNode; screens: Record<string, ComponentType> }) {
  const [name, setName] = useState(current)
  useEffect(() => {
    const onChange = () => setName(current())
    window.addEventListener('hashchange', onChange)
    return () => window.removeEventListener('hashchange', onChange)
  }, [])
  const Screen = name ? screens[name] : undefined
  return Screen ? <Screen /> : <>{home}</>
}
`

function screenSource(component: string, heading: string, tailwind: boolean, libSpec: string): string {
  const cls = (c: string) => (tailwind ? ` className="${c}"` : '')
  return `import { goBack } from '${libSpec}'

export default function ${component}() {
  return (
    <main${cls('mx-auto max-w-3xl px-6 py-12')}>
      <button type="button" onClick={goBack}${cls('text-sm underline')}>
        ← Back
      </button>
      <h1${cls('mt-6 text-3xl font-bold')}>${heading}</h1>
    </main>
  )
}
`
}

const REGISTRY_HEADER = `// ${MARK}
// Every screen the app can show, by the name after "#/" in the address.
`

interface Entry { slug: string; component: string }

/** The registry is ours, so it is read back by its own shape and rewritten whole. */
function registryEntries(code: string): Entry[] {
  return [...code.matchAll(/^\s*'([a-z0-9-]+)':\s*([A-Za-z_$][\w$]*),?\s*$/gm)].map((m) => ({ slug: m[1]!, component: m[2]! }))
}

function registrySource(entries: Entry[]): string {
  return REGISTRY_HEADER +
    entries.map((e) => `import ${e.component} from './${e.component}'\n`).join('') +
    `\nexport const screens = {\n` + entries.map((e) => `  '${e.slug}': ${e.component},\n`).join('') + `}\n`
}

// ───────────────────────── the engine ─────────────────────────

export function linkToScreen(root: string, req: NavigateRequest): NavigateResult {
  const m = STAMP.exec(req.srcLoc ?? '')
  if (!m) return { ok: false, error: `bad source location "${String(req.srcLoc)}"` }
  const rel = m[1]!
  const line = Number(m[2])
  const col = Number(m[3])
  const rootAbs = resolve(root)
  const abs = resolve(root, rel)
  if (!abs.startsWith(rootAbs)) return { ok: false, error: 'that source location escapes the app root' }

  const raw = typeof req.screen === 'string' ? req.screen.trim() : ''
  const slug = screenSlug(raw)
  if (!slug) {
    return {
      ok: false,
      error: 'the box the arrow points at has no name, so I don\'t know what the new screen is. Write its name in the box (or type it) and run again.',
    }
  }
  if (slug.length > 40) return { ok: false, error: `"${raw.slice(0, 40)}…" is too long for a screen name — a word or two is enough` }

  const router = existingRouter(root)
  const reactRouter = router === 'react-router-dom' || router === 'react-router'
  if (router && !reactRouter) {
    return {
      ok: false,
      error: `this app already uses ${router} to decide what is on each page, and adding screens to it isn't built yet. ` +
        `Nothing was changed.`,
    }
  }

  // ── where the app is mounted ──
  const mainRel = MAIN_CANDIDATES.find((f) => existsSync(join(root, f)))
  if (!mainRel && !reactRouter) return { ok: false, error: 'I couldn\'t find where the app starts (src/main.tsx), so I can\'t add a second screen. Nothing was changed.' }
  const mainAbs = mainRel ? join(root, mainRel) : ''

  // ── the trigger ──
  let code: string
  try {
    code = readFileSync(abs, 'utf8')
  } catch {
    return { ok: false, error: `cannot read ${rel}` }
  }
  let ast
  try {
    ast = parseTs(code)
  } catch {
    return { ok: false, error: `cannot parse ${rel} — fix what is broken there and try again` }
  }
  let open: NodePath<t.JSXOpeningElement> | undefined
  traverse(ast, {
    JSXOpeningElement(path: NodePath<t.JSXOpeningElement>) {
      const loc = path.node.loc
      if (loc && loc.start.line === line && loc.start.column + 1 === col) open = path
    },
  })
  if (!open) return { ok: false, error: `no element at ${req.srcLoc} (stale stamp?)` }
  const tag = hostTag(open.node)
  if (tag !== 'button' && tag !== 'a') {
    return {
      ok: false,
      error: `an arrow to a new screen has to start at a button or a link, and that is ${tag ? `a <${tag}>` : 'a component'}. ` +
        `Start the arrow on the button people will click. Nothing was changed.`,
    }
  }
  const route = `#/${slug}`
  const href = tag === 'a' ? attrNamed(open.node, 'href') : null
  if (tag === 'button' && attrNamed(open.node, 'onClick')) {
    return {
      ok: false,
      error: 'that button already does something when it is clicked, and I won\'t replace it. Draw the arrow from a button that does nothing yet. Nothing was changed.',
    }
  }
  if (href) {
    const v = href.value
    const literal = v?.type === 'StringLiteral' ? v.value : null
    if (literal == null || !(literal === '' || literal === '#' || literal.startsWith('#/'))) {
      return {
        ok: false,
        error: `that link already goes somewhere (${literal ?? 'an address worked out in code'}), and I won't repoint it. Nothing was changed.`,
      }
    }
  }

  if (abs === mainAbs) {
    return { ok: false, error: 'that button is in the file that starts the app, which I keep out of the way. Nothing was changed.' }
  }

  // An app with react-router: the page goes into its own route table (s2c-041).
  if (reactRouter) {
    return linkToRouterScreen(
      { root, rel, abs, code, open, tag, pkg: router!, slug, component: pascal(slug), title: screenTitle(raw) },
      usesTailwind(root),
    )
  }

  const component = pascal(slug)
  const libAbs = join(root, LIB_FILE)
  const regAbs = join(root, REGISTRY_FILE)
  const screenRel = `src/screens/${component}.tsx`
  const screenAbs = join(root, screenRel)
  const files: string[] = []

  // ── everything is decided; plan every write before doing any ──
  const writes: Array<{ abs: string; rel: string; text: string }> = []

  // lib
  if (existsSync(libAbs)) {
    if (!readFileSync(libAbs, 'utf8').includes(MARK)) {
      return { ok: false, error: `${LIB_FILE} already exists and isn't one I wrote, so I won't overwrite it. Nothing was changed.` }
    }
  } else {
    writes.push({ abs: libAbs, rel: LIB_FILE, text: LIB_SOURCE })
  }

  // registry + screen
  let registry = existsSync(regAbs) ? readFileSync(regAbs, 'utf8') : null
  if (registry != null && !registry.includes(MARK)) {
    return { ok: false, error: `${REGISTRY_FILE} already exists and isn't one I wrote, so I won't overwrite it. Nothing was changed.` }
  }
  const entry = new RegExp(`^\\s*'${slug}':`, 'm')
  const reused = registry != null && entry.test(registry)
  if (!reused) {
    if (existsSync(screenAbs)) {
      return { ok: false, error: `${screenRel} already exists, so I won't overwrite it. Give the new screen a different name. Nothing was changed.` }
    }
    writes.push({
      abs: screenAbs, rel: screenRel,
      text: screenSource(component, screenTitle(raw), usesTailwind(root), specifierFor(dirname(screenAbs), libAbs)),
    })
    const entries = registry == null ? [] : registryEntries(registry)
    if (registry != null && entries.length === 0) {
      return { ok: false, error: `${REGISTRY_FILE} has been edited into a shape I don't recognise, so I won't touch it. Nothing was changed.` }
    }
    entries.push({ slug, component })
    registry = registrySource(entries)
    writes.push({ abs: regAbs, rel: REGISTRY_FILE, text: registry })
  }

  // main: mount the screens around <App />
  const mainCode = readFileSync(mainAbs, 'utf8')
  if (!/\bScreens\b/.test(mainCode)) {
    const mounted = mountScreens(mainCode, dirname(mainAbs), libAbs, regAbs)
    if (typeof mounted !== 'string') return { ok: false, error: mounted.error }
    writes.push({ abs: mainAbs, rel: mainRel!, text: mounted })
  }

  // the trigger itself
  const triggerCode = pointTrigger(code, open, tag, route, slug, dirname(abs), libAbs)
  writes.push({ abs, rel, text: triggerCode })

  for (const w of writes) {
    mkdirSync(dirname(w.abs), { recursive: true })
    writeFileSync(w.abs, w.text)
    if (!files.includes(w.rel)) files.push(w.rel)
  }

  const label = screenTitle(raw)
  const existing = reused ? registryEntries(registry ?? '').find((e) => e.slug === slug) : undefined
  return {
    ok: true,
    route,
    screenFile: reused ? undefined : screenRel,
    screenAt: existing ? `src/screens/${existing.component}.tsx` : screenRel,
    title: label,
    files,
    reused,
    change: reused
      ? `pointed the ${tag === 'a' ? 'link' : 'button'} at the "${label}" screen that was already there (${route})`
      : `added a "${label}" screen (${screenRel}) and made the ${tag === 'a' ? 'link' : 'button'} open it (${route})`,
  }
}

/** main.tsx with `<App />` wrapped in `<Screens>`, or why not. */
function mountScreens(code: string, fromDir: string, libAbs: string, regAbs: string): string | { error: string } {
  let ast
  try {
    ast = parseTs(code)
  } catch {
    return { error: 'the file that starts the app doesn\'t parse, so I left it alone. Nothing was changed.' }
  }
  // the component imported from a relative './App'-like file
  let appName: string | null = null
  traverse(ast, {
    ImportDeclaration(path: NodePath<t.ImportDeclaration>) {
      const src = path.node.source.value
      if (!src.startsWith('.') || !/\/App(\.[jt]sx?)?$/.test(src)) return
      const def = path.node.specifiers.find((s) => s.type === 'ImportDefaultSpecifier')
      if (def) appName = def.local.name
    },
  })
  if (!appName) return { error: 'I couldn\'t find where the app\'s main component is shown (an import from ./App), so I can\'t add a second screen. Nothing was changed.' }
  let site: t.JSXElement | null = null
  traverse(ast, {
    JSXElement(path: NodePath<t.JSXElement>) {
      const n = path.node.openingElement.name
      if (!site && n.type === 'JSXIdentifier' && n.name === appName) site = path.node
    },
  })
  const el = site as t.JSXElement | null
  if (!el || el.start == null || el.end == null) {
    return { error: `I couldn't find <${String(appName)} /> where the app starts, so I can't add a second screen. Nothing was changed.` }
  }
  const original = code.slice(el.start, el.end)
  let out = code.slice(0, el.start) + `<Screens home={${original}} screens={screens} />` + code.slice(el.end)
  const at = importAnchor(parseTs(code), code)
  const imports =
    `import { Screens } from '${specifierFor(fromDir, libAbs)}'\n` +
    `import { screens } from '${specifierFor(fromDir, regAbs)}'\n`
  // importAnchor points after the last import; the wrap is always below it
  out = out.slice(0, at) + (at > 0 && out[at - 1] !== '\n' ? '\n' : '') + imports + out.slice(at)
  return out
}

/** The trigger's file with the button/link pointed at the screen. */
function pointTrigger(
  code: string, open: NodePath<t.JSXOpeningElement>, tag: 'a' | 'button',
  route: string, slug: string, fromDir: string, libAbs: string,
): string {
  const node = open.node
  if (tag === 'a') {
    const href = attrNamed(node, 'href')
    if (href && href.start != null && href.end != null) {
      return code.slice(0, href.start) + `href="${route}"` + code.slice(href.end)
    }
    return insertAttr(code, node, `href="${route}"`)
  }
  let out = insertAttr(code, node, `onClick={() => openScreen('${slug}')}`)
  if (!/\bopenScreen\b/.test(code)) {
    const at = importAnchor(parseTs(code), code)
    const imp = `import { openScreen } from '${specifierFor(fromDir, libAbs)}'\n`
    out = out.slice(0, at) + (at > 0 && out[at - 1] !== '\n' ? '\n' : '') + imp + out.slice(at)
  }
  return out
}

/** Insert an attribute right after the tag name, on its own line when the attributes are stacked. */
function insertAttr(code: string, node: t.JSXOpeningElement, attr: string): string {
  const nameEnd = node.name.end!
  const first = node.attributes[0]
  if (first && first.start != null) {
    const lineStart = code.lastIndexOf('\n', first.start - 1) + 1
    const before = code.slice(lineStart, first.start)
    if (before.trim() === '') return code.slice(0, first.start) + `${attr}\n${before}` + code.slice(first.start)
  }
  return code.slice(0, nameEnd) + ` ${attr}` + code.slice(nameEnd)
}

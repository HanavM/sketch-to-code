/**
 * Create the endpoint the page is already asking for.
 *
 * The other two backend moves start from something you can see: a list on the
 * screen, a form you can point at. This one starts from something you can't —
 * a request the page made that nothing answered. It exists because that failure
 * is both extremely common and unusually badly reported.
 *
 * Here is the shape of it. A dev server serving a single-page app answers an
 * unknown path with index.html, so that client-side routing works. That is the
 * right behaviour, and it means a fetch to an endpoint that does not exist gets
 * back **status 200, content-type text/html** — a page, not a 404. The app then
 * calls .json() on it and throws `Unexpected token '<'`, which names neither the
 * URL nor the actual problem. Nobody reads that error and thinks "ah, the route
 * file is missing".
 *
 * The overlay watches fetches, so it knows the exact URL and that the answer was
 * HTML. All that is left is to write the file — and this writes the smallest one
 * that can be correct: an empty list. Not a guess at the records, because there
 * is nothing here to guess from, and a fabricated record that looks plausible is
 * worse than an empty one: the page renders, the developer believes it, and the
 * fiction lives until something depends on it.
 *
 * So the deal is narrow and honest. One keypress turns a misleading parse error
 * into a working endpoint that answers `[]`, in a file whose whole body is the
 * one line worth editing.
 */
import { existsSync, mkdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'

const MARK = '@generated by sketch-to-code create-the-endpoint'
/** Also in api.ts and form.ts: a route this tool wrote is one it may replace. */
const OURS = /@generated by sketch-to-code/

export interface StubRequest {
  /**
   * The path the page asked for — `/api/orders`, or just `orders`. Taken as the
   * page reported it rather than as a bare name so the caller does not have to
   * parse a URL correctly for the file to land in the right place.
   */
  path: string
  /** What GET answers with. A list unless the caller knows otherwise. */
  kind?: 'list' | 'object'
}

export interface StubResult {
  ok: boolean
  /** The URL it now answers on, e.g. `/api/orders`. */
  route?: string
  /** Repo-relative, e.g. `server/api/orders.ts`. */
  file?: string
  files?: string[]
  change?: string
  error?: string
}

/** `/api/orders?since=1` and `orders/` both name the route `orders`. */
function routeName(raw: string): string | null {
  const bare = raw
    .split(/[?#]/)[0]!
    .replace(/^https?:\/\/[^/]+/i, '')
    .replace(/^\/+/, '')
    .replace(/^api\//, '')
    .replace(/\/+$/, '')
  return /^[a-z][a-z0-9_-]{0,63}$/.test(bare) ? bare : null
}

function routeSource(route: string, name: string, kind: 'list' | 'object'): string {
  const empty = kind === 'list' ? '[]' : '{}'
  const type = kind === 'list' ? 'unknown[]' : 'Record<string, unknown>'
  return (
    `/**\n` +
    ` * ${route} — created because the page asked for it and nothing answered.\n` +
    ` *\n` +
    ` * It was getting index.html back with a 200, which is what a dev server does\n` +
    ` * with a path it does not know, and why the error said "Unexpected token '<'"\n` +
    ` * instead of naming this file. Now the request is answered.\n` +
    ` *\n` +
    ` * What it answers with is ${empty}, because nothing here knew what the records\n` +
    ` * are — that part is yours, and it is the line below. A plain module on\n` +
    ` * purpose: no framework imports, nothing to install, mountable as-is.\n` +
    ` *\n` +
    ` *   express   app.get('${route}', (_req, res) => { res.json(GET()) })\n` +
    ` *   next      export function GET() { return Response.json(${name}) }\n` +
    ` *\n` +
    ` * ${MARK}\n` +
    ` */\n` +
    `export const ${name}: ${type} = ${empty}\n` +
    `\n` +
    `export function GET(): ${type} {\n` +
    `  return ${name}\n` +
    `}\n`
  )
}

export function stubRoute(root: string, req: StubRequest): StubResult {
  const name = routeName(req.path)
  if (!name) {
    return {
      ok: false,
      error:
        `"${req.path}" does not name a route this can create — it needs one plain segment ` +
        `like /api/orders, using lowercase letters, digits, dashes and underscores. ` +
        `A nested path (/api/team/members) has to be written by hand.`,
    }
  }
  const rel = join('server', 'api', `${name}.ts`)
  const abs = join(root, rel)
  if (existsSync(abs)) {
    // Either the miss was something else entirely (a route that throws, a
    // method it does not export), or this already ran. Both are cases where
    // overwriting would destroy the answer rather than supply one.
    return {
      ok: false,
      error:
        `${rel} already exists, so the page is not missing this endpoint — the request is ` +
        `failing for another reason. Open that file: a route that throws, or that does not ` +
        `export a handler for this method, fails without being absent.`,
    }
  }
  const kind = req.kind === 'object' ? 'object' : 'list'
  const route = `/api/${name}`
  const text = routeSource(route, name, kind)
  mkdirSync(dirname(abs), { recursive: true })
  writeFileSync(abs, text)
  return {
    ok: true,
    route,
    file: rel,
    files: [rel],
    change:
      `${route} now answers with ${kind === 'list' ? 'an empty list' : 'an empty object'} from ` +
      `${rel} — put the real data in that file`,
  }
}

/** Whether a route file at this name was written by this tool. */
export function isGeneratedRoute(source: string): boolean {
  return OURS.test(source)
}

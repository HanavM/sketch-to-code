/** 'ContactForm' / 'CONTACT_FORM' / 'Invite a teammate' → 'contact-form' / 'invite-a-teammate'. */
function slug(raw: string): string {
  return raw
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .join('-')
    .toLowerCase()
}

/** 'contacts' → 'Contacts', for a type name. */
const pascal = (raw: string): string =>
  raw
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .map((w) => w[0]!.toUpperCase() + w.slice(1))
    .join('')

/** 'contacts' → 'contactsForm', for a second hook in one component. */
const camel = (raw: string): string => {
  const p = pascal(raw)
  return p ? p[0]!.toLowerCase() + p.slice(1) : ''
}

/**
 * One record of this, named as a collection of them.
 *
 * Only ever applied to the LAST segment, so 'sign-up' becomes 'sign-ups' and
 * not 'signs-up'. A word that is already plural is left alone — `InvitesForm`
 * should reach '/api/invites', not '/api/inviteses'.
 */
function plural(word: string): string {
  const at = word.lastIndexOf('-')
  const head = at < 0 ? '' : word.slice(0, at + 1)
  const tail = at < 0 ? word : word.slice(at + 1)
  if (/(ss|sh|ch|x|z)$/.test(tail)) return `${head}${tail}es`
  if (/s$/.test(tail)) return word
  if (/[^aeiou]y$/.test(tail)) return `${head}${tail.slice(0, -1)}ies`
  return `${head}${tail}s`
}

/** POSIX, extension-less, always relative — a specifier a bundler accepts. */
function specifierFor(fromDir: string, toAbs: string): string {
  const spec = relative(fromDir, toAbs).replace(/\\/g, '/').replace(/\.[jt]sx?$/, '')
  return spec.startsWith('.') ? spec : `./${spec}`
}

const indentAt = (code: string, index: number): string => {
  const lineStart = code.lastIndexOf('\n', index - 1) + 1
  return /^[ \t]*/.exec(code.slice(lineStart, index))![0]
}

/**
 * Is this offset the first thing on its line?
 *
 * It decides whether an inserted attribute is a new line or a space away from
 * the one before it. A form whose attributes are stacked one per line is the
 * common case in anything Tailwind-shaped, and welding `name="email"` onto the
 * end of a 90-character className line is the kind of diff people revert.
 */
function onOwnLine(code: string, index: number): boolean {
  const lineStart = code.lastIndexOf('\n', index - 1) + 1
  return code.slice(lineStart, index).trim() === ''
}

const listOf = (parts: string[]): string =>
  parts.length <= 1
    ? (parts[0] ?? 'nothing')
    : `${parts.slice(0, -1).join(', ')} and ${parts[parts.length - 1]!}`

/** '1st', '2nd', '3rd', '4th' — so a refusal can point at one of five inputs. */
function ordinal(n: number): string {
  const tens = n % 100
  if (tens >= 11 && tens <= 13) return `${String(n)}th`
  switch (n % 10) {
    case 1:
      return `${String(n)}st`
    case 2:
      return `${String(n)}nd`
    case 3:
      return `${String(n)}rd`
    default:
      return `${String(n)}th`
  }
}

/** The enclosing function's name, when it has one worth quoting. */
function fnName(fn: NodePath): string | null {
  const n = fn.node
  if ((n.type === 'FunctionDeclaration' || n.type === 'FunctionExpression') && n.id) return n.id.name
  const parent = fn.parentPath
  if (parent?.isVariableDeclarator() && parent.node.id.type === 'Identifier') return parent.node.id.name
  return null
}

/** The tag as written: `input`, `select`, `Field`, `Ui.Input`. */
function tagName(open: t.JSXOpeningElement): string {
  const n = open.name
  if (n.type === 'JSXIdentifier') return n.name
  if (n.type === 'JSXMemberExpression') {
    const obj = n.object.type === 'JSXIdentifier' ? n.object.name : '…'
    return `${obj}.${n.property.name}`
  }
  return '…'
}

const isHostForm = (open: t.JSXOpeningElement): boolean =>
  open.name.type === 'JSXIdentifier' && open.name.name === 'form'

/**
 * The nearest enclosing `<form>` — the real element, not a component.
 *
 * A `<ContactForm>` or a `<Form>` from a library is somebody else's submit
 * handling, and wiring ours in next to it would produce two handlers for one
 * gesture. The walk therefore stops at nothing and reports what it passed, so
 * the refusal can name the component it found instead.
 */
function enclosingForm(el: NodePath): { form: NodePath<t.JSXElement> | null; sawComponent: string | null } {
  let sawComponent: string | null = null
  for (let at: NodePath | null = el; at; at = at.parentPath) {
    if (!at.isJSXElement()) continue
    const open = at.node.openingElement
    if (isHostForm(open)) return { form: at, sawComponent: null }
    const tag = tagName(open)
    if (sawComponent == null && /form/i.test(tag) && /^[A-Z]/.test(tag)) sawComponent = tag
  }
  return { form: null, sawComponent }
}

/**
 * The component the hook call has to go into.
 *
 * `getFunctionParent()` from inside JSX can land on a callback — a `.map()` over
 * fields, an `onChange` — and a function that is itself an argument to a call is
 * not where React runs hooks, so callbacks are stepped over.
 */
function componentOwner(from: NodePath): NodePath<t.Function> | null {
  let fn = from.getFunctionParent()
  while (fn) {
    const p: NodePath | null = fn.parentPath
    if (p?.isCallExpression() && (p.node.arguments as t.Node[]).includes(fn.node)) {
      fn = p.getFunctionParent()
      continue
    }
    return fn
  }
  return null
}

const attrNamed = (open: t.JSXOpeningElement, name: string): t.JSXAttribute | null => {
  for (const a of open.attributes) {
    if (a.type === 'JSXAttribute' && a.name.type === 'JSXIdentifier' && a.name.name === name) return a
  }
  return null
}

/** The value of `x="literal"`, or null when it is written as an expression. */
function literalAttr(open: t.JSXOpeningElement, name: string): string | null {
  const a = attrNamed(open, name)
  if (!a) return null
  if (a.value?.type === 'StringLiteral') return a.value.value
  if (a.value?.type === 'JSXExpressionContainer' && a.value.expression.type === 'StringLiteral') {
    return a.value.expression.value
  }
  return null
}

/** `required` / `required={true}` — and NOT `required={false}` or `required={x}`. */
function isRequired(open: t.JSXOpeningElement): boolean {
  const a = attrNamed(open, 'required')
  if (!a) return false
  if (a.value == null) return true
  return a.value.type === 'JSXExpressionContainer' && a.value.expression.type === 'BooleanLiteral'
    ? a.value.expression.value
    : false
}

/** A field of the form, once it is known to be storable. */
interface Field {
  /** input / select / textarea */
  tag: string
  /** the key it is stored under, and the `name` the browser will submit */
  key: string
  required: boolean
  /** the `name="…"` this has to add, when the field had none */
  add: { at: number; text: string } | null
}

/** A key that can be written as `x:` in an interface, or has to be quoted. */
const propKey = (key: string): string => (/^[A-Za-z_$][\w$]*$/.test(key) ? key : `'${key}'`)

/**
 * The hook, written once per project.
 *
 * Kept as source text rather than generated, because there is nothing about it
 * to vary: every form made real submits the same way, and the only thing that
 * differs is the URL.
 */
const HOOK_SOURCE = `/**
 * One form, one URL, four states, no dependencies.
 *
 * Everything about a submit that people get wrong the first time is settled
 * here, once. The values are read out of the form element synchronously, before
 * anything is awaited, because the element is reset on success and
 * \`currentTarget\` is gone by the time a promise resolves. \`preventDefault()\`
 * happens first, so a missing server cannot cause a full page navigation.
 *
 * And the status always lands somewhere. A dead endpoint, a 500, a route that
 * answers \`{ error }\` — each of those ends as 'error' with something to read,
 * never as a rejected promise and never as a spinner stuck on 'saving'. That is
 * the whole reason this is a hook and not three lines in an onSubmit.
 *
 * ${MARK}
 */
import { useState } from 'react'
import type { FormEvent } from 'react'

export type FormStatus = 'idle' | 'saving' | 'saved' | 'error'

export function ${HOOK_NAME}(url: string): {
  onSubmit: (e: FormEvent<HTMLFormElement>) => void
  status: FormStatus
  error: string | null
} {
  const [status, setStatus] = useState<FormStatus>('idle')
  const [error, setError] = useState<string | null>(null)

  function onSubmit(e: FormEvent<HTMLFormElement>): void {
    // first, and unconditionally: without it a failed POST becomes a full page
    // navigation and the typed-in values are gone
    e.preventDefault()
    const el = e.currentTarget
    // read now, not inside the async body: el.reset() runs on success and
    // e.currentTarget is null once this handler has returned
    const values: Record<string, string> = {}
    for (const [key, value] of new FormData(el).entries()) {
      if (typeof value === 'string') values[key] = value
    }

    setStatus('saving')
    setError(null)
    void (async () => {
      try {
        const res = await fetch(url, {
          method: 'POST',
          headers: { 'content-type': 'application/json' },
          body: JSON.stringify(values),
        })
        // a body carrying \`error\` is the route saying no, which is not the same
        // as the server saying nothing — but both are things to show, not throw
        const body: unknown = await res.json().catch(() => null)
        const said =
          body && typeof body === 'object' && 'error' in body
            ? String((body as { error: unknown }).error)
            : null
        if (!res.ok || said != null) {
          setStatus('error')
          setError(said ?? \`\${String(res.status)} \${res.statusText}\`.trim())
          return
        }
        el.reset()
        setStatus('saved')
      } catch (err) {
        // the endpoint is not mounted yet, or the network is gone. Either way
        // the person is owed a sentence rather than a silent nothing.
        setStatus('error')
        setError(err instanceof Error ? err.message : \`\${url} did not answer\`)
      }
    })()
  }

  return { onSubmit, status, error }
}
`

/** Does this file already export something called `useForm`? */
function exportsHook(code: string): boolean {
  let found = false
  let ast
  try {
    ast = parseTs(code)
  } catch {
    return false
  }
  for (const stmt of ast.program.body) {
    if (stmt.type !== 'ExportNamedDeclaration') continue
    const d = stmt.declaration
    if (d?.type === 'FunctionDeclaration' && d.id?.name === HOOK_NAME) found = true
    if (d?.type === 'VariableDeclaration') {
      for (const decl of d.declarations) {
        if (decl.id.type === 'Identifier' && decl.id.name === HOOK_NAME) found = true
      }
    }
    for (const s of stmt.specifiers) {
      if (s.type === 'ExportSpecifier') {
        const as = s.exported.type === 'Identifier' ? s.exported.name : s.exported.value
        if (as === HOOK_NAME) found = true
      }
    }
  }
  return found
}

/**
 * The route file.
 *
 * A plain module with no framework imports, for the same reason api.ts writes
 * one: the framework is not decided yet, and the promise is that this file can
 * be mounted later by whatever the prototype becomes. GET and POST are the two
 * halves of a store, and between them they are the whole feature — the page can
 * submit, and someone can read back what was submitted, with nothing installed.
 *
 * The validation is deliberately small and deliberately not a library. It
 * refuses a body that is not an object, keeps only the keys the form actually
 * has, and requires the ones the JSX marked `required`. Unknown keys are
 * dropped rather than stored, because an endpoint that writes whatever it is
 * handed is a different kind of file from the one this claims to be.
 */
function routeSource(
  routeName: string,
  url: string,
  fields: Field[],
  ownerName: string,
  fromRel: string,
  dataRel: string,
): string {
  const typeName = `${pascal(routeName)}Record`
  const required = fields.filter((f) => f.required)
  const names = fields.map((f) => f.key)
  const sample = fields[0]?.key ?? 'field'
  const props = fields
    .map((f) => `  ${propKey(f.key)}${f.required ? '' : '?'}: string`)
    .join('\n')
  const list = (keys: string[]): string => `[${keys.map((k) => `'${k}'`).join(', ')}]`
  return (
    `/**\n` +
    ` * ${url} — what the <form> in ${ownerName} (${fromRel}) submits.\n` +
    ` *\n` +
    ` * Deliberately a plain module: no framework imports, nothing to install, and\n` +
    ` * nothing running yet. It exports a GET that reads the records back and a POST\n` +
    ` * that appends one, which is the smallest thing each of these can mount as-is:\n` +
    ` *\n` +
    ` *   express   app.get('${url}', (_req, res) => { res.json(GET()) })\n` +
    ` *             app.post('${url}', (req, res) => { res.json(POST(req, req.body)) })\n` +
    ` *   next      export function GET() { return Response.json(read()) }\n` +
    ` *   test      expect(POST(null, { ${sample}: 'x' })).toMatchObject({ ${sample}: 'x' })\n` +
    ` *\n` +
    ` * Records live in ${dataRel}, read and written with node:fs on every\n` +
    ` * call. That is the one thing in this file NOT to tidy up. Importing the store\n` +
    ` * instead — an \`import\` of the .json file above — would put it in Vite's module\n` +
    ` * graph, so every submit would touch a watched file, hot-reload the page, and\n` +
    ` * blank the form somebody is still filling in. An imported JSON module is also\n` +
    ` * cached, so the second read would answer with the first read's data.\n` +
    ` *\n` +
    ` * ${MARK}\n` +
    ` */\n` +
    `import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'\n` +
    `\n` +
    `/** Resolved from this file, not from the working directory — a server can be started anywhere. */\n` +
    `const STORE = new URL('../data/${routeName}.json', import.meta.url)\n` +
    `\n` +
    `/** Every key this accepts. A body's other keys are dropped, never stored. */\n` +
    `export const FIELDS: readonly string[] = ${list(names)}\n` +
    `/** Marked \`required\` in the form, so a record without them is not a record. */\n` +
    `export const REQUIRED: readonly string[] = ${list(required.map((f) => f.key))}\n` +
    `\n` +
    `/** One submission. \`id\` and \`createdAt\` are stamped here; the rest is the form. */\n` +
    `export interface ${typeName} {\n` +
    `  id: string\n` +
    `  createdAt: string\n` +
    `${props}\n` +
    `}\n` +
    `\n` +
    `export function GET(): ${typeName}[] {\n` +
    `  return read()\n` +
    `}\n` +
    `\n` +
    `export function POST(req: unknown, body: unknown): ${typeName} | { error: string } {\n` +
    `  // \`req\` is accepted and ignored, so the signature already matches what a\n` +
    `  // framework hands a handler when this stops being a plain module\n` +
    `  void req\n` +
    `  if (body == null || typeof body !== 'object' || Array.isArray(body)) {\n` +
    `    return { error: 'expected a JSON object of form fields' }\n` +
    `  }\n` +
    `  const sent = body as Record<string, unknown>\n` +
    `\n` +
    `  // only the form's own fields, and only as the strings a form sends\n` +
    `  const values: Record<string, string> = {}\n` +
    `  for (const field of FIELDS) {\n` +
    `    const value = sent[field]\n` +
    `    if (typeof value === 'string' && value.trim() !== '') values[field] = value.trim()\n` +
    `  }\n` +
    `  const missing = REQUIRED.filter((field) => values[field] == null)\n` +
    `  if (missing.length > 0) {\n` +
    `    return { error: \`\${missing.join(', ')} \${missing.length === 1 ? 'is' : 'are'} required\` }\n` +
    `  }\n` +
    `\n` +
    `  const saved = {\n` +
    `    id: Math.random().toString(36).slice(2, 10),\n` +
    `    createdAt: new Date().toISOString(),\n` +
    `    ...values,\n` +
    `  } as ${typeName}\n` +
    `\n` +
    `  const all = read()\n` +
    `  all.push(saved)\n` +
    `  // the store is created on first write, so a fresh checkout has no empty file\n` +
    `  // to explain and nothing to commit until something has actually been sent\n` +
    `  mkdirSync(new URL('.', STORE), { recursive: true })\n` +
    `  writeFileSync(STORE, \`\${JSON.stringify(all, null, 2)}\\n\`)\n` +
    `  return saved\n` +
    `}\n` +
    `\n` +
    `/** The records so far. Absent, empty or half-written all mean "none yet". */\n` +
    `function read(): ${typeName}[] {\n` +
    `  if (!existsSync(STORE)) return []\n` +
    `  try {\n` +
    `    const parsed: unknown = JSON.parse(readFileSync(STORE, 'utf8'))\n` +
    `    return Array.isArray(parsed) ? (parsed as ${typeName}[]) : []\n` +
    `  } catch {\n` +
    `    // a truncated file from a process that died mid-save is not worth a crash\n` +
    `    // on every read for the rest of the afternoon\n` +
    `    return []\n` +
    `  }\n` +
    `}\n`
  )
}

export function makeFormReal(root: string, req: FormRequest): FormResult {
  const m = STAMP.exec(req.srcLoc ?? '')
  if (!m) return { ok: false, error: `bad source location "${String(req.srcLoc)}"` }
  const rel = m[1]!
  const line = Number(m[2])
  const col = Number(m[3])

  const abs = resolve(root, rel)
  if (!abs.startsWith(resolve(root))) return { ok: false, error: 'that source location escapes the app root' }

  let code: string
  try {
    code = readFileSync(abs, 'utf8')
  } catch {
    return { ok: false, error: `cannot read ${rel}` }
  }
  let ast
  try {
    ast = parseTs(code)
  } catch {
    return { ok: false, error: `cannot parse ${rel} — fix what is broken there and try again` }
  }

  // ── the element, and the form around it ──
  let open: NodePath<t.JSXOpeningElement> | undefined
  traverse(ast, {
    JSXOpeningElement(path: NodePath<t.JSXOpeningElement>) {
      const loc = path.node.loc
      if (loc && loc.start.line === line && loc.start.column + 1 === col) open = path
    },
  })
  if (!open) return { ok: false, error: `no element at ${req.srcLoc} (stale stamp?)` }

  const { form, sawComponent } = enclosingForm(open)
  if (!form) {
    if (sawComponent) {
      return {
        ok: false,
        error:
          `that element is inside <${sawComponent}>, which is a component rather than a real <form>, so its submit is ` +
          `handled somewhere else. Point at a <form> element — or make ${sawComponent}'s own <form> real, in the file ` +
          `that declares it.`,
      }
    }
    return {
      ok: false,
      error:
        `that element is not inside a <form>, so there is nothing to submit. Wrap the fields in a <form> element and ` +
        `point at it — or at any field inside it — again.`,
    }
  }
  const formOpen = form.node.openingElement
  const formLine = formOpen.loc?.start.line

  // ── the fields, which are already written down ──
  const fields: Field[] = []
  const seen = new Map<string, string>()
  const counts = new Map<string, number>()
  let fault: string | null = null
  form.traverse({
    JSXOpeningElement(path: NodePath<t.JSXOpeningElement>) {
      if (fault) return
      const node = path.node
      const tag = tagName(node)
      if (!FIELD_TAGS.has(tag)) return
      // a nested <form> is invalid HTML, but if someone has written one its
      // fields belong to it and not to ours
      const inner = enclosingForm(path.parentPath).form
      if (inner && inner.node !== form.node) return
      // a submit button is an <input> that carries no value worth storing
      if (tag === 'input' && NOT_A_FIELD.has((literalAttr(node, 'type') ?? '').toLowerCase())) return

      const nth = (counts.get(tag) ?? 0) + 1
      counts.set(tag, nth)
      const where = `the ${ordinal(nth)} <${tag}> in that form`

      const nameAttr = attrNamed(node, 'name')
      const name = literalAttr(node, 'name')
      const id = literalAttr(node, 'id')
      let key: string
      let add: Field['add'] = null
      if (nameAttr && name == null) {
        fault =
          `${where} has a computed name (\`name={…}\`), so there is no key to store its value under. Give it a plain ` +
          `\`name="something"\` and try again.`
        return
      } else if (nameAttr && name === '') {
        fault =
          `${where} has an empty \`name=""\`, and a form does not submit a field with no name. Give it a real name and ` +
          `try again.`
        return
      } else if (name != null && name !== '') {
        key = name
      } else if (id != null && id !== '') {
        key = id
        const at = attrNamed(node, 'id')!
        if (at.start == null || at.end == null) {
          fault = `${where} has no source positions — reload the page and try again.`
          return
        }
        add = {
          at: at.end,
          text: onOwnLine(code, at.start) ? `\n${indentAt(code, at.start)}name="${id}"` : ` name="${id}"`,
        }
      } else {
        fault =
          `${where} has neither an \`id\` nor a \`name\`, and a form only submits fields that have a name — there is ` +
          `nothing here to call it, and guessing one would store the value under a key nobody wrote. Add ` +
          `\`name="something"\` to it (or an \`id\`, which this will copy) and try again.`
        return
      }
      const before = seen.get(key)
      if (before != null) {
        fault =
          `two fields in that form are both called "${key}" — ${before} and ${where} — so one would overwrite the ` +
          `other in every saved record. Give them different names and try again.`
        return
      }
      seen.set(key, `the ${ordinal(nth)} <${tag}>`)
      fields.push({ tag, key, required: isRequired(node), add })
    },
  })
  if (fault) return { ok: false, error: fault }
  if (fields.length === 0) {
    return {
      ok: false,
      error:
        `that <form>${formLine ? ` (line ${String(formLine)})` : ''} has no fields in it — no <input>, <select> or ` +
        `<textarea> — so a submit would save an empty record. Add the fields first, then make it real.`,
    }
  }

  // ── already ours? ──
  const onSubmit = attrNamed(formOpen, 'onSubmit')
  const handler =
    onSubmit?.value?.type === 'JSXExpressionContainer' ? onSubmit.value.expression : null
  if (
    handler?.type === 'MemberExpression' &&
    !handler.computed &&
    handler.object.type === 'Identifier' &&
    handler.property.type === 'Identifier' &&
    handler.property.name === 'onSubmit'
  ) {
    const bound = form.scope.getBinding(handler.object.name)
    const init = bound?.path.isVariableDeclarator() ? bound.path.node.init : null
    if (init?.type === 'CallExpression' && init.callee.type === 'Identifier' && init.callee.name === HOOK_NAME) {
      const arg = init.arguments[0]
      const already = arg?.type === 'StringLiteral' ? arg.value : null
      const file = already != null ? `server/api/${already.replace(/^\/api\//, '')}.ts` : 'the route file it posts to'
      return {
        ok: false,
        error:
          `that form is already real: it posts to ${already ?? 'an endpoint'} through ` +
          `\`${handler.object.name} = ${HOOK_NAME}(…)\`. ` +
          `Edit ${file} to change what it stores, or the JSX to change the fields.`,
      }
    }
  }
  // An `{...props}` after our attribute wins over it, silently, and the form
  // would go on doing nothing — which is the exact bug this edit came to fix.
  const spreadAfter = formOpen.attributes.some(
    (a) => a.type === 'JSXSpreadAttribute' && onSubmit?.start != null && (a.start ?? 0) > onSubmit.start,
  )
  if (spreadAfter) {
    return {
      ok: false,
      error:
        `that <form> has a \`{...}\` spread after its \`onSubmit\`, so whatever the spread carries would override the ` +
        `submit handler and the form would still save nothing. Move the spread before the other attributes and try again.`,
    }
  }

  // ── the component the hook has to live in ──
  const owner = componentOwner(form)
  if (!owner) {
    return {
      ok: false,
      error:
        `that <form> is not rendered inside a function, so there is no component to submit from. Render it from a ` +
        `component and try again.`,
    }
  }
  const ownerName = fnName(owner)
  if (!ownerName || !COMPONENT.test(ownerName)) {
    return {
      ok: false,
      error:
        `that <form> is rendered by ${ownerName ? `${ownerName}()` : 'an anonymous function'}, which is not a React ` +
        `component, so a hook cannot run there. Move the form into the component that renders it and try again.`,
    }
  }
  const body = owner.node.body
  if (body.type !== 'BlockStatement' || body.start == null) {
    return {
      ok: false,
      error:
        `${ownerName} returns its JSX directly, so there is no room in it for the submit state. Give it a block body ` +
        `(\`${ownerName} = () => { return … }\`) and try again.`,
    }
  }

  // ── names ──
  const given = req.name != null && req.name !== ''
  const base = slug(given ? req.name! : ownerName)
  // 'ContactForm' → 'contact-form' → 'contact': the word "form" names the thing
  // on screen, not the records it stores
  const trimmed = given ? base : base.replace(/(^|-)form$/, '')
  if (!trimmed) {
    return {
      ok: false,
      error:
        `${ownerName} does not say what one of its records is called, so this cannot name the route. Pass a name for ` +
        `it — 'invites', 'signups', 'messages' — and try again.`,
    }
  }
  const routeName = given ? trimmed : plural(trimmed)
  if (!ROUTE_NAME.test(routeName)) {
    return {
      ok: false,
      error:
        `"${given ? req.name! : ownerName}" does not make a usable route name — it has to start with a letter and use ` +
        `lowercase letters, digits, dashes and underscores, like 'invites'.`,
    }
  }
  const url = `/api/${routeName}`
  const routeRel = `server/api/${routeName}.ts`
  const dataRel = `server/data/${routeName}.json`
  const routeAbs = join(root, routeRel)
  if (existsSync(routeAbs)) {
    let existing = ''
    try {
      existing = readFileSync(routeAbs, 'utf8')
    } catch {
      existing = ''
    }
    // Nothing is overwritten here, ours included: a route that has been
    // answering POSTs has records behind it, and rewriting the file that reads
    // them is not a decision this gesture gets to make.
    return {
      ok: false,
      error: existing.includes(MARK)
        ? `${routeRel} already exists — this tool wrote it for a form already, and ${dataRel} may hold records that ` +
          `came in through it. Pass a different name for this route, or delete that file and its data file if they ` +
          `are stale.`
        : `${routeRel} already exists and was not written by this tool, so making this form real would overwrite ` +
          `somebody's endpoint. Pass a different name for the route, or delete that file if it is stale.`,
    }
  }

  const local = owner.scope.hasBinding(LOCAL) ? `${camel(routeName)}Form` : LOCAL
  if (owner.scope.hasBinding(local)) {
    return {
      ok: false,
      error:
        `${rel} already uses the names \`${LOCAL}\` and \`${local}\`, and this needs one of them for the submit state. ` +
        `Rename one of them and try again.`,
    }
  }

  // Reusing an existing `useForm` import is what makes a second form in the same
  // file work; a second import line would be a duplicate declaration.
  const hookAbs = join(root, HOOK_FILE)
  let hookImported = false
  let hookClash = false
  for (const stmt of ast.program.body) {
    if (stmt.type !== 'ImportDeclaration') continue
    const specAbs = resolve(dirname(abs), stmt.source.value)
    const sameModule =
      ['', '.ts', '.tsx', '.js', '.jsx'].some((e) => specAbs + e === hookAbs) ||
      // an aliased path ('@/lib/useForm') resolves to nothing from here, but it
      // is plainly the same module, and refusing it would be a lie
      /(^|\/)lib\/useForm(\.[jt]sx?)?$/.test(stmt.source.value)
    for (const s of stmt.specifiers) {
      if (s.local.name !== HOOK_NAME) continue
      if (sameModule && s.type === 'ImportSpecifier') hookImported = true
      else hookClash = true
    }
  }
  if (!hookImported && (hookClash || owner.scope.hasBinding(HOOK_NAME))) {
    return {
      ok: false,
      error: `${rel} already has its own \`${HOOK_NAME}\`, which is not the hook this writes. Rename it and try again.`,
    }
  }

  // ── the hook file: write it once, never over someone else's ──
  let hookSource: string | null = null
  if (existsSync(hookAbs)) {
    let existing = ''
    try {
      existing = readFileSync(hookAbs, 'utf8')
    } catch {
      return { ok: false, error: `cannot read ${HOOK_FILE}` }
    }
    // A project that already has this hook keeps it: theirs may do retries,
    // optimistic state, a base URL. Only the shape matters, and the import has
    // to resolve.
    if (!exportsHook(existing)) {
      return {
        ok: false,
        error:
          `${HOOK_FILE} already exists but does not export \`${HOOK_NAME}\`, so the import would not resolve. Rename ` +
          `that file, or add a \`${HOOK_NAME}(url)\` export to it, and try again.`,
      }
    }
  } else {
    hookSource = HOOK_SOURCE
  }

  // ── build every edit, then check everything parses before writing ──
  const firstStmt = body.body[0]
  const bodyIndent = firstStmt?.start != null ? indentAt(code, firstStmt.start) : `${indentAt(code, owner.node.start ?? 0)}  `
  const hookCall = `const ${local} = ${HOOK_NAME}('${url}')`
  const importLine = hookImported ? '' : `import { ${HOOK_NAME} } from '${specifierFor(dirname(abs), hookAbs)}'\n`

  const edits: { start: number; end: number; text: string }[] = [
    { start: body.start + 1, end: body.start + 1, text: `\n${bodyIndent}${hookCall}` },
  ]
  for (const f of fields) {
    if (f.add) edits.push({ start: f.add.at, end: f.add.at, text: f.add.text })
  }

  // onSubmit: replace the placeholder, or add one AFTER the existing attributes
  // so it is the last word on the subject
  const handlerAttr = `onSubmit={${local}.onSubmit}`
  if (onSubmit?.start != null && onSubmit.end != null) {
    edits.push({ start: onSubmit.start, end: onSubmit.end, text: handlerAttr })
  } else {
    const attrs = formOpen.attributes
    const last = attrs.length > 0 ? attrs[attrs.length - 1] : null
    if (last?.start != null && last.end != null) {
      const text = onOwnLine(code, last.start) ? `\n${indentAt(code, last.start)}${handlerAttr}` : ` ${handlerAttr}`
      edits.push({ start: last.end, end: last.end, text })
    } else if (formOpen.name.end != null) {
      edits.push({ start: formOpen.name.end, end: formOpen.name.end, text: ` ${handlerAttr}` })
    } else {
      return { ok: false, error: `that <form> has no source positions — reload the page and try again` }
    }
  }

  // the status line, as the form's last child: an edit nobody can see happening
  // is an edit nobody trusts
  const closing = form.node.closingElement
  if (!closing || closing.start == null) {
    return {
      ok: false,
      error:
        `that <form /> has no closing tag, so there is nowhere in it to say whether a submit worked. Write it as ` +
        `<form>…</form> and try again.`,
    }
  }
  const kids = form.node.children.filter((c) => !(c.type === 'JSXText' && c.value.trim() === ''))
  const lastKid = kids.length > 0 ? kids[kids.length - 1] : null
  const statusAt = lastKid?.end ?? null
  const statusIndent =
    lastKid?.start != null && onOwnLine(code, lastKid.start)
      ? indentAt(code, lastKid.start)
      : `${indentAt(code, closing.start)}  `
  const statusLine = `<p aria-live="polite">{${local}.status === 'saved' ? 'Saved' : ${local}.error}</p>`
  const at = statusAt ?? closing.start
  edits.push({ start: at, end: at, text: statusAt != null ? `\n${statusIndent}${statusLine}` : `${statusLine}\n${statusIndent}` })

  if (importLine) {
    // the anchor comes from the AST, not from a `^import` match — imports.ts
    // explains the bug that taught every engine here to ask babel
    const anchor = importAnchor(ast, code)
    // anchor 0 means the file had no imports at all, so the new line would
    // otherwise weld itself onto whatever the file actually opens with
    edits.push({ start: anchor, end: anchor, text: anchor === 0 ? `${importLine}\n` : importLine })
  }

  // later offsets first, so each earlier edit's positions are still the ones
  // babel reported
  edits.sort((a, b) => b.start - a.start)
  let next = code
  for (const e of edits) next = next.slice(0, e.start) + e.text + next.slice(e.end)

  const routeText = routeSource(routeName, url, fields, ownerName, rel, dataRel)
  const outputs: [string, string][] = [
    [rel, next],
    [routeRel, routeText],
  ]
  if (hookSource) outputs.push([HOOK_FILE, hookSource])
  // nothing is written until every file that would be written parses
  for (const [what, text] of outputs) {
    try {
      parseTs(text)
    } catch (err) {
      return { ok: false, error: `making that form real would leave ${what} unparseable (${String(err)})` }
    }
  }

  mkdirSync(dirname(routeAbs), { recursive: true })
  writeFileSync(routeAbs, routeText)
  if (hookSource) {
    mkdirSync(dirname(hookAbs), { recursive: true })
    writeFileSync(hookAbs, hookSource)
  }
  writeFileSync(abs, next)

  const named = fields.filter((f) => f.add).map((f) => f.key)
  return {
    ok: true,
    route: routeRel,
    files: hookSource ? [rel, routeRel, HOOK_FILE] : [rel, routeRel],
    fields: fields.map((f) => f.key),
    change:
      `${ownerName} now saves ${listOf(fields.map((f) => f.key))} to ${dataRel} through POST ${url}` +
      (named.length > 0 ? `, naming ${listOf(named.map((n) => `\`${n}\``))} on the way` : ''),
  }
}

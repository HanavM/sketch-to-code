/**
 * Make this form real.
 *
 * A form is the most convincing lie a prototype tells. Every field is there,
 * the labels are right, the button says "Send invite" and has a hover state —
 * and `onSubmit={(e) => e.preventDefault()}` throws the whole thing away. It
 * demos perfectly and stores nothing, which is why it survives: nobody can see
 * the part that is missing. The work to finish it is, once again, the same work
 * every time — a place to put the records, a handler that collects the values,
 * a request, four states to hold while it is in flight, and the field names
 * nobody added because the browser did not need them to render.
 *
 * So it happens by pointing at the form. The stamp on any element inside it
 * names a JSX node, and from that node the enclosing `<form>` is an ancestor
 * walk rather than a guess. Everything else the edit needs is written down in
 * the JSX already: which fields there are, what they are called, which ones are
 * `required`. Nothing here is inferred from prose, and the two things that
 * genuinely cannot be known — what the records should be called, and whether a
 * field with no `id` and no `name` was meant to be stored — are refusals.
 *
 * Three departures worth defending.
 *
 * The store is read and written with `node:fs` on every call, and the route
 * file says so in a comment, because `import records from '../data/x.json'` is
 * exactly what a tidy-minded person would replace it with. That import puts the
 * store in Vite's module graph: every submit would then write a watched file,
 * hot-reload the page, and blank the form the user is still filling in. It also
 * caches, so the second read answers with the first read's data.
 *
 * The `name` attributes are added, not required. `new FormData(form)` only sees
 * fields that have one, and a prototype's fields almost never do — they were
 * written for `htmlFor`/`id` pairing, which is all the browser needed. Deriving
 * `name` from `id` is the one inference here, and it is safe because it is
 * reversible and visible in the diff. Inventing a name for a field that has
 * neither is not, so that refuses and says which field.
 *
 * And the hook goes INSIDE the component, as its first statement. `useForm()`
 * at module scope runs on import, outside a render, and takes the whole page
 * down with it — api.ts learned this the hard way and this file inherits the
 * lesson rather than re-learning it.
 *
 * What it will not do: no server is started, nothing is mounted, no validation
 * library, no schema, no auth. It writes a plain module a person can mount
 * later, and it points the form at the URL that module is meant to answer.
 */

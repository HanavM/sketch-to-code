/**
 * Ease, efficiency and speed beside likeness, per page and per round (INBOX 2026-10-26 15:49).
 * Zero tokens: reads each round's plan (marks a person draws, notes and words typed) and each
 * page's latest run digest (built/runs/*.json: tokens, codegen turns and their time, and from
 * n253 on the drawing, reading and whole-run times).
 *
 *   node tests/rounds/ease.mjs            # writes tests/rounds/EASE.md, prints round averages as JSON
 *
 * Columns:
 *   marks    strokes drawn (pen marks the plan puts on the canvas)
 *   notes    typed notes, words  the words typed into them
 *   draw s   seconds to draw the marks and type the notes (recorded from n253 on)
 *   read s   seconds from Run until the reading is shown to confirm (how fast the first answer shows)
 *   build s  seconds of codegen (sum of codegen turns' own time), or whole run when that is all we have
 *   tokens   billed tokens (input + output, cache reads excluded)
 *   fixes    codegen turns after the first build (repair rounds): how much correcting it took
 */
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const ROOT = new URL('./', import.meta.url).pathname
const rounds = readdirSync(ROOT).filter((d) => /^round\d+$/.test(d)).map((d) => +d.slice(5)).sort((a, b) => a - b)
const words = (t) => String(t).split(/\s+/).filter(Boolean).length
const avg = (xs) => { const v = xs.filter((x) => x != null && Number.isFinite(x)); return v.length ? v.reduce((a, b) => a + b, 0) / v.length : null }
const r0 = (x) => (x == null ? '–' : Math.round(x).toLocaleString('en-US'))

const out = []
for (const n of rounds) {
  const dir = join(ROOT, `round${n}`)
  let specs = []
  try { specs = (await import(join(dir, 'auto.mjs'))).default } catch { /* rounds without auto plans */ }
  const byId = new Map(specs.map((s) => [s.id, s]))
  const runs = join(dir, 'built', 'runs')
  const pages = []
  for (const f of existsSync(runs) ? readdirSync(runs).filter((x) => x.endsWith('.json')).sort() : []) {
    const d = JSON.parse(readFileSync(join(runs, f), 'utf8'))
    const s = byId.get(d.id)
    const e = d.ease ?? {}
    const sends = d.sends ?? []
    const codegenMs = sends.length && sends.every((x) => x.ms != null) ? sends.reduce((a, x) => a + x.ms, 0) : null
    pages.push({
      id: d.id,
      likeness: d.likeness ? Math.round(d.likeness.overall * 100) : null,
      marks: e.marks ?? s?.strokes?.length ?? null,
      notes: e.notes ?? s?.notes?.length ?? null,
      words: e.words ?? (s ? s.notes.reduce((a, x) => a + words(x.text), 0) : null),
      drawS: e.drawMs != null ? e.drawMs / 1000 : null,
      readS: e.readingMs != null ? e.readingMs / 1000 : null,
      buildS: codegenMs != null ? codegenMs / 1000 : e.runMs != null ? e.runMs / 1000 : null,
      tokens: d.tokens ? d.tokens.input + d.tokens.output : null,
      fixes: sends.length ? sends.filter((x) => x.kind !== 'build').length + Math.max(0, sends.filter((x) => x.kind === 'build').length - 1) : null,
    })
  }
  if (!pages.length) continue
  const k = (key) => avg(pages.map((p) => p[key]))
  out.push({ round: n, pages, avg: { likeness: k('likeness'), marks: k('marks'), words: k('words'), drawS: k('drawS'), readS: k('readS'), buildS: k('buildS'), tokens: k('tokens'), fixes: k('fixes') } })
}

const lines = ['# Ease, efficiency and speed beside likeness', '',
  'Generated by `node tests/rounds/ease.mjs` from each page\'s latest live build. Marks = pen strokes drawn; words = words typed in notes;',
  'read = seconds until the reading shows (recorded from n253 on); build = seconds of code writing; tokens = billed (in + out);',
  'fixes = code-writing turns after the first build. A dash means that run predates the field.',
  'Before n253, marks and words come from the round\'s current plan, which is re-planned as rules improve, so an old page\'s words',
  'may be more than its build was given. Correcting is also visible as live re-runs per page in each round\'s NOTES.md.', '',
  '## Per round (averages over built pages)', '',
  '| round | pages | likeness | marks | words | draw s | read s | build s | tokens | fixes |', '|---|---|---|---|---|---|---|---|---|---|']
for (const r of out) {
  const a = r.avg
  lines.push(`| ${r.round} | ${r.pages.length} | ${r0(a.likeness)}% | ${r0(a.marks)} | ${r0(a.words)} | ${r0(a.drawS)} | ${r0(a.readS)} | ${r0(a.buildS)} | ${r0(a.tokens)} | ${a.fixes == null ? '–' : a.fixes.toFixed(1)} |`)
}
lines.push('', '## Per page', '')
for (const r of [...out].reverse()) {
  lines.push(`### Round ${r.round}`, '', '| page | likeness | marks | notes | words | draw s | read s | build s | tokens | fixes |', '|---|---|---|---|---|---|---|---|---|---|')
  for (const p of r.pages) lines.push(`| ${p.id} | ${r0(p.likeness)}% | ${r0(p.marks)} | ${r0(p.notes)} | ${r0(p.words)} | ${r0(p.drawS)} | ${r0(p.readS)} | ${r0(p.buildS)} | ${r0(p.tokens)} | ${p.fixes ?? '–'} |`)
  lines.push('')
}
writeFileSync(join(ROOT, 'EASE.md'), lines.join('\n'))
console.log(JSON.stringify(out.map((r) => ({ round: r.round, ...Object.fromEntries(Object.entries(r.avg).map(([k, v]) => [k, v == null ? null : Math.round(v)])) }))))
